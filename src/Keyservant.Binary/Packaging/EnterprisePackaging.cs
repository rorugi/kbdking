using System.Globalization;
using System.Security;
using System.Security.Cryptography;
using System.Text;

namespace Keyservant.Binary.Packaging;

/// <summary>
/// Deployment packages for organisations: a WiX source for an MSI (Group Policy, Intune line-of-business,
/// SCCM) and a folder ready for the Microsoft Win32 Content Prep Tool (Intune Win32 apps).
/// </summary>
public static class EnterprisePackaging
{
    /// <summary>
    /// The KLID an MSI registers. MSIs are built before the target PC is known, so the ID can't be allocated
    /// there; it is the layout's own ID when set, otherwise derived from the DLL name (same input, same ID).
    /// </summary>
    public static string MsiKlid(LayoutPackage package) =>
        package.LayoutId?.ToUpperInvariant() ?? string.Create(CultureInfo.InvariantCulture, $"A{Hash(package.DllFileName) & 0xFFF:X3}{package.LanguageId:X4}");

    /// <summary>"Layout Id" for MSI installs, from a range Windows' own layouts don't use (5000–5FFF).</summary>
    public static string MsiLayoutId(LayoutPackage package) =>
        string.Create(CultureInfo.InvariantCulture, $"5{Hash(package.DllFileName + package.LanguageId) & 0xFFF:X3}");

    /// <summary>
    /// Writes a WiX v5 project (Package.wxs plus the DLLs) into <paramref name="directory"/>. Build it with
    /// <c>wix build Package.wxs -arch x64 -o layout.msi</c>. Returns the path of Package.wxs.
    /// </summary>
    public static string WriteWixProject(LayoutPackage package, string directory)
    {
        Directory.CreateDirectory(Path.Combine(directory, "x64"));
        File.WriteAllBytes(Path.Combine(directory, "x64", package.DllFileName), package.DllX64);
        if (package.DllWow64 is not null)
        {
            Directory.CreateDirectory(Path.Combine(directory, "wow64"));
            File.WriteAllBytes(Path.Combine(directory, "wow64", package.DllFileName), package.DllWow64);
        }

        var klid = MsiKlid(package);
        string E(string s) => SecurityElement.Escape(s) ?? "";
        var version = MsiVersion(package.Version);
        var upgradeCode = DeterministicGuid("keyservant-msi-upgrade:" + package.DllFileName.ToLowerInvariant());
        var sb = new StringBuilder();
        sb.Append(CultureInfo.InvariantCulture, $"""
            <!-- Generated by Keyservant. Build with: wix build Package.wxs -arch x64 -o {E(Path.GetFileNameWithoutExtension(package.DllFileName))}.msi -->
            <Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">
              <Package Name="{E(package.Name)} (keyboard layout)" Manufacturer="Keyservant" Version="{version}"
                       UpgradeCode="{upgradeCode}" Scope="perMachine" Compressed="yes" Language="1033">
                <MajorUpgrade DowngradeErrorMessage="A newer version of this keyboard layout is already installed." />
                <MediaTemplate EmbedCab="yes" />

                <StandardDirectory Id="System64Folder">
                  <Component Id="LayoutDll64" Bitness="always64">
                    <File Id="LayoutDll64" Source="x64\{E(package.DllFileName)}" Name="{E(package.DllFileName)}" KeyPath="yes" />
                  </Component>
                  <Component Id="LayoutRegistration" Bitness="always64">
                    <RegistryKey Root="HKLM" Key="SYSTEM\CurrentControlSet\Control\Keyboard Layouts\{klid}">
                      <RegistryValue Name="Layout File" Type="string" Value="{E(package.DllFileName)}" KeyPath="yes" />
                      <RegistryValue Name="Layout Text" Type="string" Value="{E(package.Name)}" />
                      <RegistryValue Name="Layout Display Name" Type="expandable" Value="@%SystemRoot%\system32\{E(package.DllFileName)},-1000" />
                      <RegistryValue Name="Layout Id" Type="string" Value="{MsiLayoutId(package)}" />
                      <RegistryValue Name="Keyservant" Type="string" Value="{E(package.Version)}" />
                    </RegistryKey>
                  </Component>
                </StandardDirectory>

            """);
        if (package.DllWow64 is not null)
        {
            sb.Append(CultureInfo.InvariantCulture, $"""
                    <StandardDirectory Id="SystemFolder">
                      <Component Id="LayoutDll32" Bitness="always32">
                        <File Id="LayoutDll32" Source="wow64\{E(package.DllFileName)}" Name="{E(package.DllFileName)}" KeyPath="yes" />
                      </Component>
                    </StandardDirectory>

                """);
        }
        sb.Append("""
              </Package>
            </Wix>

            """);
        var path = Path.Combine(directory, "Package.wxs");
        File.WriteAllText(path, sb.ToString().Replace("\r\n", "\n", StringComparison.Ordinal));
        return path;
    }

    /// <summary>
    /// Writes an Intune Win32 app source folder: the standalone installer, install/uninstall commands and a
    /// detection script. Wrap it with IntuneWinAppUtil.exe -c folder -s setup.exe -o output.
    /// </summary>
    public static void WriteIntuneFolder(LayoutPackage package, string stubPath, string directory)
    {
        Directory.CreateDirectory(directory);
        var setup = Path.Combine(directory, "setup.exe");
        package.WriteInstaller(stubPath, setup);
        File.WriteAllText(Path.Combine(directory, "install.cmd"), "@echo off\r\n\"%~dp0setup.exe\" /silent\r\nexit /b %errorlevel%\r\n");
        File.WriteAllText(Path.Combine(directory, "uninstall.cmd"), "@echo off\r\n\"%~dp0setup.exe\" /uninstall /silent\r\nexit /b %errorlevel%\r\n");
        var dll = package.DllFileName.Replace("'", "''", StringComparison.Ordinal);
        var ver = package.Version.Replace("'", "''", StringComparison.Ordinal);
        File.WriteAllText(Path.Combine(directory, "detect.ps1"), $$"""
            # Intune detection script for the keyboard layout "{{package.Name}}" (generated by Keyservant).
            $root = 'HKLM:\SYSTEM\CurrentControlSet\Control\Keyboard Layouts'
            $match = Get-ChildItem $root | Where-Object {
                $p = Get-ItemProperty $_.PSPath
                $p.'Layout File' -eq '{{dll}}' -and $p.Keyservant -eq '{{ver}}'
            }
            if ($match -and (Test-Path (Join-Path $env:SystemRoot 'System32\{{dll}}'))) { Write-Output 'Installed'; exit 0 }
            exit 1

            """.Replace("\n", "\r\n", StringComparison.Ordinal));
        File.WriteAllText(Path.Combine(directory, "README.txt"), $"""
            Keyboard layout "{package.Name}" for Microsoft Intune (Win32 app)

            1. Wrap this folder:   IntuneWinAppUtil.exe -c <this folder> -s setup.exe -o <output folder>
            2. In Intune, add a Windows app (Win32) with the .intunewin file:
               Install command:    install.cmd
               Uninstall command:  uninstall.cmd
               Install behavior:   System
               Detection rule:     Custom script -> detect.ps1
            3. Assign it to devices or users. Users switch to the layout with Win+Space.

            """.Replace("\n", "\r\n", StringComparison.Ordinal));
    }

    private static string MsiVersion(string version)
    {
        var parts = version.Split('.').Select(p => int.TryParse(p, out var n) ? Math.Clamp(n, 0, 255) : 0).Concat([0, 0, 0]).Take(3);
        return string.Join('.', parts);
    }

    private static uint Hash(string s)
    {
        var bytes = SHA256.HashData(Encoding.UTF8.GetBytes(s.ToLowerInvariant()));
        return BitConverter.ToUInt32(bytes, 0);
    }

    /// <summary>A name-based GUID (RFC 4122 version 5 style), stable across builds.</summary>
    private static string DeterministicGuid(string name)
    {
        var hash = SHA1.HashData(Encoding.UTF8.GetBytes(name));
        hash[6] = (byte)((hash[6] & 0x0F) | 0x50);
        hash[8] = (byte)((hash[8] & 0x3F) | 0x80);
        return new Guid(hash.AsSpan(0, 16)).ToString("D").ToUpperInvariant();
    }
}
