using System.Globalization;
using System.Text;
using System.Xml;
using System.Xml.Linq;
using Kbdking.Core.Geometry;
using Kbdking.Core.Model;
using Kbdking.Core.Templates;

namespace Kbdking.Core.Formats;

/// <summary>
/// macOS keyboard layouts (.keylayout, the XML format Ukelele edits). Keys map by physical position;
/// Option corresponds to AltGr. Dead keys become the keylayout state machine (actions, states, terminators).
/// </summary>
public sealed class MacKeylayoutFormat : ILayoutFormat
{
    public string Id => "keylayout";
    public string DisplayName => "macOS keyboard layout";
    public IReadOnlyList<string> Extensions { get; } = [".keylayout"];
    public bool CanRead => true;
    public bool CanWrite => true;

    private const int MapBase = 0, MapShift = 1, MapCaps = 2, MapOption = 3, MapShiftOption = 4, MapCapsOption = 5, MapControl = 6;

    // ---------------------------------------------------------------- writing

    public void Write(KeyboardLayout layout, Stream output, ConversionReport report)
    {
        var text = Serialize(layout, report);
        output.Write(new UTF8Encoding(false).GetBytes(text));
    }

    public static string Serialize(KeyboardLayout source, ConversionReport report)
    {
        var layout = Compose.ComposeCompiler.Compile(source).Layout;
        if (layout.Modifiers.Columns.Any(c => (c.Bits & ~(ModifierBits.Shift | ModifierBits.AltGr)) != 0 && c.Bits != ModifierBits.Ctrl && c.Bits != (ModifierBits.Shift | ModifierBits.Ctrl)))
            report.Warn("Shift states other than Shift, AltGr (Option) and Ctrl are not exported.");
        if (source.Compose is not null) report.Warn("Compose sequences are exported as dead-key states.");

        // Characters that act as dead-key bases need actions; collect them.
        var baseChars = new HashSet<char>();
        foreach (var d in layout.DeadKeys) foreach (var e in d.Entries) baseChars.Add(e.Base);

        var sb = new StringBuilder();
        var id = -(Math.Abs(StableHash(layout.Metadata.Name)) % 30000 + 1000);
        sb.Append("<?xml version=\"1.1\" encoding=\"UTF-8\"?>\n");
        sb.Append("<!DOCTYPE keyboard SYSTEM \"file://localhost/System/Library/DTDs/KeyboardLayout.dtd\">\n");
        sb.Append(CultureInfo.InvariantCulture, $"<!-- Generated by kbdking from \"{Esc(layout.Metadata.Name).Replace("--", "- -", StringComparison.Ordinal).TrimEnd('-')}\" -->\n");
        sb.Append(CultureInfo.InvariantCulture, $"<keyboard group=\"126\" id=\"{id}\" name=\"{Esc(layout.Metadata.Name)}\" maxout=\"{Math.Max(1, MaxOutput(layout))}\">\n");
        sb.Append("  <layouts>\n    <layout first=\"0\" last=\"17\" modifiers=\"Modifiers\" mapSet=\"ANSI\"/>\n  </layouts>\n");
        sb.Append("""
              <modifierMap id="Modifiers" defaultIndex="0">
                <keyMapSelect mapIndex="0"><modifier keys="command?"/></keyMapSelect>
                <keyMapSelect mapIndex="1"><modifier keys="anyShift caps? command?"/></keyMapSelect>
                <keyMapSelect mapIndex="2"><modifier keys="caps"/></keyMapSelect>
                <keyMapSelect mapIndex="3"><modifier keys="anyOption"/></keyMapSelect>
                <keyMapSelect mapIndex="4"><modifier keys="anyShift caps? anyOption command?"/></keyMapSelect>
                <keyMapSelect mapIndex="5"><modifier keys="caps anyOption"/></keyMapSelect>
                <keyMapSelect mapIndex="6"><modifier keys="anyShift? caps? anyOption? command? anyControl"/></keyMapSelect>
              </modifierMap>

            """.Replace("\r", "", StringComparison.Ordinal));
        sb.Append("  <keyMapSet id=\"ANSI\">\n");
        for (var map = 0; map <= MapControl; map++)
        {
            sb.Append(CultureInfo.InvariantCulture, $"    <keyMap index=\"{map}\">\n");
            foreach (var entry in PhysicalKeyCodes.All)
            {
                if (entry.MacCode is not { } code) continue;
                var target = entry.Extended ? layout.ScanCodes.E0.GetValueOrDefault((byte)entry.ScanCode, ScanCodeTarget.None) : layout.ScanCodes[entry.ScanCode];
                var vk = target.VirtualKey;
                if (target.Flags.HasFlag(ScanCodeFlags.Numpad) && entry.ScanCode == 0x53) vk = VirtualKeys.Decimal;
                var key = target.IsNone ? null : layout.FindKey(vk);
                if (key is null) continue;
                var output = OutputFor(layout, key, map);
                if (output is null) continue;
                if (output.IsDead)
                    sb.Append(CultureInfo.InvariantCulture, $"      <key code=\"{code}\" action=\"{DeadActionId(output.Accent)}\"/>\n");
                else if (output.Text.Length == 1 && baseChars.Contains(output.Text[0]))
                    sb.Append(CultureInfo.InvariantCulture, $"      <key code=\"{code}\" action=\"{CharActionId(output.Text[0])}\"/>\n");
                else
                    sb.Append(CultureInfo.InvariantCulture, $"      <key code=\"{code}\" output=\"{Esc(output.Text)}\"/>\n");
            }
            // Keys every Mac layout needs.
            sb.Append("      <key code=\"36\" output=\"&#x000D;\"/>\n      <key code=\"48\" output=\"&#x0009;\"/>\n");
            sb.Append("      <key code=\"51\" output=\"&#x0008;\"/>\n      <key code=\"53\" output=\"&#x001B;\"/>\n");
            sb.Append("      <key code=\"76\" output=\"&#x0003;\"/>\n      <key code=\"117\" output=\"&#x007F;\"/>\n");
            sb.Append("      <key code=\"123\" output=\"&#x001C;\"/>\n      <key code=\"124\" output=\"&#x001D;\"/>\n");
            sb.Append("      <key code=\"125\" output=\"&#x001F;\"/>\n      <key code=\"126\" output=\"&#x001E;\"/>\n");
            sb.Append("    </keyMap>\n");
        }
        sb.Append("  </keyMapSet>\n");

        // Actions: dead keys and composing characters.
        var accents = layout.DeadKeys.Select(d => d.Accent).ToHashSet();
        foreach (var k in layout.Keys) foreach (var o in k.Outputs.Values) if (o.IsDead) accents.Add(o.Accent);
        if (accents.Count > 0 || baseChars.Count > 0)
        {
            sb.Append("  <actions>\n");
            foreach (var accent in accents.Order())
            {
                sb.Append(CultureInfo.InvariantCulture, $"    <action id=\"{DeadActionId(accent)}\">\n");
                sb.Append(CultureInfo.InvariantCulture, $"      <when state=\"none\" next=\"{StateId(accent)}\"/>\n");
                AppendCompositionWhens(sb, layout, accent);
                sb.Append("    </action>\n");
            }
            foreach (var c in baseChars.Where(c => !accents.Contains(c)).Order())
            {
                sb.Append(CultureInfo.InvariantCulture, $"    <action id=\"{CharActionId(c)}\">\n");
                sb.Append(CultureInfo.InvariantCulture, $"      <when state=\"none\" output=\"{Esc(c.ToString())}\"/>\n");
                AppendCompositionWhens(sb, layout, c);
                sb.Append("    </action>\n");
            }
            sb.Append("  </actions>\n");

            sb.Append("  <terminators>\n");
            foreach (var accent in accents.Order())
            {
                // The terminator is typed before a key that doesn't compose; Windows types the accent there too.
                sb.Append(CultureInfo.InvariantCulture, $"    <when state=\"{StateId(accent)}\" output=\"{Esc(accent.ToString())}\"/>\n");
            }
            sb.Append("  </terminators>\n");
        }
        sb.Append("</keyboard>\n");
        return sb.ToString();
    }

    private static void AppendCompositionWhens(StringBuilder sb, KeyboardLayout layout, char baseChar)
    {
        foreach (var d in layout.DeadKeys)
        {
            if (d.Find(baseChar) is not { } e) continue;
            if (e.Chained) sb.Append(CultureInfo.InvariantCulture, $"      <when state=\"{StateId(d.Accent)}\" next=\"{StateId(e.Result)}\"/>\n");
            else sb.Append(CultureInfo.InvariantCulture, $"      <when state=\"{StateId(d.Accent)}\" output=\"{Esc(e.Result.ToString())}\"/>\n");
        }
    }

    private static KeyOutput? OutputFor(KeyboardLayout layout, KeyDefinition key, int map)
    {
        KeyOutput? Get(ShiftState s) => layout.Modifiers.Canonicalize(s) is { } c ? key.Outputs.GetValueOrDefault(c) : null;
        KeyOutput? CapsOf(ShiftState s, bool altGr)
        {
            if (key.CapsOutputs is { } caps && !altGr) return caps.GetValueOrDefault(s) ?? Get(s);
            var applies = altGr ? key.Attributes.HasFlag(KeyAttributes.CapsLockAltGr) : key.Attributes.HasFlag(KeyAttributes.CapsLock);
            return applies ? Get(new ShiftState(s.Bits ^ ModifierBits.Shift)) : Get(s);
        }
        return map switch
        {
            MapBase => Get(ShiftState.Base),
            MapShift => Get(ShiftState.Shift),
            MapCaps => CapsOf(ShiftState.Base, false),
            MapOption => Get(ShiftState.AltGr),
            MapShiftOption => Get(ShiftState.ShiftAltGr),
            MapCapsOption => CapsOf(ShiftState.AltGr, true),
            MapControl => Get(ShiftState.Ctrl) ?? ControlChar(key.VirtualKey),
            _ => null,
        };
    }

    private static KeyOutput? ControlChar(byte vk) => vk is >= (byte)'A' and <= (byte)'Z' ? KeyOutput.Of((char)(vk - 0x40)) : null;

    private static int MaxOutput(KeyboardLayout l) => l.Keys.SelectMany(k => k.Outputs.Values).Where(o => !o.IsDead).Select(o => o.Text.Length).DefaultIfEmpty(1).Max();

    private static string DeadActionId(char accent) => $"dead_{(int)accent:X4}";
    private static string CharActionId(char c) => $"char_{(int)c:X4}";
    private static string StateId(char accent) => $"s{(int)accent:X4}";

    private static string Esc(string s)
    {
        var sb = new StringBuilder();
        foreach (var c in s)
        {
            if (c is '&' or '<' or '>' or '"' or '\'' || char.IsControl(c))
                sb.Append(CultureInfo.InvariantCulture, $"&#x{(int)c:X4};");
            else sb.Append(c);
        }
        return sb.ToString();
    }

    private static int StableHash(string s)
    {
        var h = 23;
        foreach (var c in s) h = unchecked(h * 31 + c);
        return h == int.MinValue ? 0 : h;
    }

    // ---------------------------------------------------------------- reading

    public KeyboardLayout Read(Stream input, ConversionReport report)
    {
        using var reader = new StreamReader(input, Encoding.UTF8, detectEncodingFromByteOrderMarks: true);
        return Parse(reader.ReadToEnd(), report);
    }

    public static KeyboardLayout Parse(string xml, ConversionReport report)
    {
        try
        {
            return ParseCore(xml, report);
        }
        catch (Exception ex) when (ex is FormatException or ArgumentException or InvalidOperationException or NullReferenceException or OverflowException)
        {
            // Attributes that aren't numbers, missing required attributes and the like.
            throw new LayoutFormatException($"Invalid keylayout file: {ex.Message}", ex);
        }
    }

    private static Dictionary<string, TValue> FirstWins<TValue>(IEnumerable<XElement> elements, string attribute, Func<XElement, TValue> value)
    {
        var d = new Dictionary<string, TValue>(StringComparer.Ordinal);
        foreach (var e in elements) d.TryAdd((string?)e.Attribute(attribute) ?? "", value(e));
        return d;
    }

    private static KeyboardLayout ParseCore(string xml, ConversionReport report)
    {
        // .NET reads XML 1.0 only; keylayout files are 1.1 mainly to allow control-character references.
        xml = xml.Replace("version=\"1.1\"", "version=\"1.0\"", StringComparison.Ordinal);
        XDocument doc;
        try
        {
            using var reader = XmlReader.Create(new StringReader(xml), new XmlReaderSettings { DtdProcessing = DtdProcessing.Ignore, CheckCharacters = false, XmlResolver = null });
            doc = XDocument.Load(reader);
        }
        catch (XmlException ex)
        {
            throw new LayoutFormatException($"Invalid keylayout XML: {ex.Message}", ex);
        }
        var kb = doc.Root ?? throw new LayoutFormatException("Empty keylayout file.");
        if (kb.Name.LocalName != "keyboard") throw new LayoutFormatException("Not a macOS keyboard layout (missing <keyboard>).");

        var layout = LayoutTemplates.UnitedStates();
        layout.Metadata = new LayoutMetadata { Name = (string?)kb.Attribute("name") ?? "Imported layout" };
        layout.Flags = LocaleFlags.None;
        layout.Keys.RemoveAll(k => !VirtualKeys.IsImplicitControlKey(k.VirtualKey));
        layout.DeadKeys.Clear();

        // Which keyMap index is used for each modifier combination.
        var layoutEl = kb.Element("layouts")?.Elements("layout").FirstOrDefault() ?? throw new LayoutFormatException("No <layout> element.");
        var mapSetId = (string?)layoutEl.Attribute("mapSet");
        var modifiersId = (string?)layoutEl.Attribute("modifiers");
        var modMap = kb.Elements("modifierMap").FirstOrDefault(m => (string?)m.Attribute("id") == modifiersId)
            ?? throw new LayoutFormatException($"modifierMap '{modifiersId}' not found.");
        var defaultIndex = (int?)modMap.Attribute("defaultIndex") ?? 0;
        int IndexFor(bool shift, bool option, bool caps, bool control)
        {
            foreach (var sel in modMap.Elements("keyMapSelect"))
            {
                foreach (var mod in sel.Elements("modifier"))
                {
                    if (Matches((string?)mod.Attribute("keys") ?? "", shift, option, caps, control)) return (int)sel.Attribute("mapIndex")!;
                }
            }
            return defaultIndex;
        }

        var keyMapSets = FirstWins(kb.Elements("keyMapSet"), "id", s => s);
        if (mapSetId is null || !keyMapSets.ContainsKey(mapSetId)) throw new LayoutFormatException($"keyMapSet '{mapSetId}' not found.");
        var actions = FirstWins(kb.Element("actions")?.Elements("action") ?? [], "id", a => a);
        var terminators = FirstWins(kb.Element("terminators")?.Elements("when") ?? [], "state", w => (string?)w.Attribute("output"));

        // Resolve a key element (with keyMap inheritance through baseMapSet/baseIndex).
        XElement? FindKey(string setId, int index, int code, int depth = 0)
        {
            if (depth > 4 || !keyMapSets.TryGetValue(setId, out var set)) return null;
            var map = set.Elements("keyMap").FirstOrDefault(m => (int?)m.Attribute("index") == index);
            if (map is null) return null;
            var key = map.Elements("key").FirstOrDefault(k => (int?)k.Attribute("code") == code);
            if (key is not null) return key;
            var baseSet = (string?)map.Attribute("baseMapSet");
            var baseIndex = (int?)map.Attribute("baseIndex");
            return baseSet is not null && baseIndex is not null ? FindKey(baseSet, baseIndex.Value, code, depth + 1) : null;
        }

        // State name → accent character, assigned from terminators (the character typed when a state is abandoned).
        var stateAccents = new Dictionary<string, char>();
        var nextPrivate = '';
        char AccentFor(string state)
        {
            if (stateAccents.TryGetValue(state, out var a)) return a;
            a = terminators.TryGetValue(state, out var t) && t is { Length: 1 } ? t[0] : nextPrivate++;
            if (stateAccents.ContainsValue(a)) a = nextPrivate++;
            stateAccents[state] = a;
            return a;
        }

        KeyOutput? Interpret(XElement keyEl)
        {
            if ((string?)keyEl.Attribute("output") is { Length: > 0 } output) return KeyOutput.Of(output);
            var actionId = (string?)keyEl.Attribute("action");
            if (actionId is null) return null;
            if (!actions.TryGetValue(actionId, out var action)) return actionId.Length > 0 ? KeyOutput.Of(actionId) : null; // inline action = output
            var none = action.Elements("when").FirstOrDefault(w => (string?)w.Attribute("state") == "none");
            if (none is null) return null;
            if ((string?)none.Attribute("next") is { } next) return KeyOutput.Dead(AccentFor(next));
            return (string?)none.Attribute("output") is { Length: > 0 } o ? KeyOutput.Of(o) : null;
        }

        var combos = new (ShiftState State, bool Shift, bool Option)[]
        {
            (ShiftState.Base, false, false), (ShiftState.Shift, true, false),
            (ShiftState.AltGr, false, true), (ShiftState.ShiftAltGr, true, true),
        };
        var usedActions = new HashSet<string>();
        foreach (var entry in PhysicalKeyCodes.All)
        {
            if (entry.MacCode is not { } code) continue;
            var template = entry.Extended ? layout.ScanCodes.E0.GetValueOrDefault((byte)entry.ScanCode, ScanCodeTarget.None) : layout.ScanCodes[entry.ScanCode];
            if (template.IsNone)
            {
                if (FindKey(mapSetId, IndexFor(false, false, false, false), code) is not null)
                    report.Warn($"Mac key code {code} (Windows scan code {entry.ScanCode:X2}) has no key in the base layout and was skipped.");
                continue;
            }
            var vk = template.Flags.HasFlag(ScanCodeFlags.Numpad) && entry.ScanCode == 0x53 ? VirtualKeys.Decimal : template.VirtualKey;
            KeyDefinition? key = null;
            foreach (var (state, shift, option) in combos)
            {
                var el = FindKey(mapSetId, IndexFor(shift, option, false, false), code);
                if (el is null) continue;
                if ((string?)el.Attribute("action") is { } a) usedActions.Add(a);
                var o = Interpret(el);
                if (o is null || !o.IsDead && o.Text.Any(char.IsControl)) continue;
                key ??= layout.GetOrAddKey(vk);
                layout.SetOutput(vk, state, o);
            }
            if (key is null) continue;
            // Caps Lock: same as Shift on letters → CAPLOK; something else → separate Caps row.
            var capsEl = FindKey(mapSetId, IndexFor(false, false, true, false), code);
            var caps = capsEl is null ? null : Interpret(capsEl);
            var shifted = key.Outputs.GetValueOrDefault(ShiftState.Shift);
            var plain = key.Outputs.GetValueOrDefault(ShiftState.Base);
            if (caps is not null && shifted is not null && caps == shifted && caps != plain) key.Attributes |= KeyAttributes.CapsLock;
            else if (caps is not null && caps != plain && !caps.IsDead && plain is { IsDead: false })
                key.CapsOutputs = new SortedDictionary<ShiftState, KeyOutput> { [ShiftState.Base] = caps, [ShiftState.Shift] = shifted ?? caps };
        }

        // Dead-key compositions from the actions' state transitions.
        foreach (var (id, action) in actions)
        {
            var none = action.Elements("when").FirstOrDefault(w => (string?)w.Attribute("state") == "none");
            char? baseChar = (string?)none?.Attribute("output") is { Length: 1 } bo ? bo[0]
                : (string?)none?.Attribute("next") is { } bn ? AccentFor(bn) : null;
            if (baseChar is null) continue;
            foreach (var w in action.Elements("when"))
            {
                var state = (string?)w.Attribute("state");
                if (state is null or "none") continue;
                var dead = layout.GetOrAddDeadKey(AccentFor(state));
                if ((string?)w.Attribute("next") is { } next) dead.Set(baseChar.Value, AccentFor(next), chained: true);
                else if ((string?)w.Attribute("output") is { } o)
                {
                    if (o.Length == 1) dead.Set(baseChar.Value, o[0]);
                    else report.Warn($"Dead-key result \"{o}\" (state {state}) has several characters, which Windows dead keys can't produce; skipped.");
                }
            }
        }
        foreach (var (state, accent) in stateAccents)
        {
            if (!terminators.ContainsKey(state)) report.Warn($"State '{state}' has no terminator; kbdking gave it the placeholder U+{(int)accent:X4}.");
        }
        if (layout.Keys.Any(k => k.Outputs.Keys.Any(s => s.Bits.HasFlag(ModifierBits.AltGr)))) layout.Flags |= LocaleFlags.AltGr;
        report.Warn("Command and Control key maps are not imported; Windows uses its own Ctrl handling.");
        LayoutFixups.AssignLetterVirtualKeys(layout);
        layout.NormalizeShiftStates();
        return layout;
    }

    /// <summary>Evaluates a keylayout modifier expression such as "anyShift caps? command?".</summary>
    private static bool Matches(string keys, bool shift, bool option, bool caps, bool control)
    {
        var have = new Dictionary<string, bool> { ["shift"] = shift, ["option"] = option, ["caps"] = caps, ["control"] = control, ["command"] = false };
        var required = new Dictionary<string, bool?>(); // true = required, null = optional
        foreach (var raw in keys.Split(' ', StringSplitOptions.RemoveEmptyEntries))
        {
            var optional = raw.EndsWith('?');
            var name = raw.TrimEnd('?').ToLowerInvariant().Replace("any", "", StringComparison.Ordinal).Replace("right", "", StringComparison.Ordinal);
            if (name.StartsWith("cmd", StringComparison.Ordinal)) name = "command";
            if (!have.ContainsKey(name)) continue;
            required[name] = optional ? null : true;
        }
        foreach (var (name, present) in have)
        {
            if (required.TryGetValue(name, out var req))
            {
                if (req == true && !present) return false;
            }
            else if (present) return false;
        }
        return true;
    }
}
