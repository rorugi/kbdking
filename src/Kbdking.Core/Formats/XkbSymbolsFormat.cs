namespace Kbdking.Core.Formats;

/// <summary>
/// Linux XKB symbols files (as in /usr/share/X11/xkb/symbols). Four levels: base, Shift, AltGr
/// (level 3) and Shift+AltGr (level 4). Dead keys use XKB's dead_* keysyms; on Linux their compositions
/// come from the Compose table, so custom compositions are written to a companion .XCompose file
/// (<see cref="WriteXCompose"/>).
/// </summary>
public sealed partial class XkbSymbolsFormat : ILayoutFormat
{
    public string Id => "xkb";
    public string DisplayName => "Linux XKB symbols";
    public IReadOnlyList<string> Extensions { get; } = [".xkb"];
    public bool CanRead => true;
    public bool CanWrite => true;

    private static readonly ShiftState[] Levels = [ShiftState.Base, ShiftState.Shift, ShiftState.AltGr, ShiftState.ShiftAltGr];

    // ---------------------------------------------------------------- writing

    public void Write(KeyboardLayout layout, Stream output, ConversionReport report) =>
        output.Write(new UTF8Encoding(false).GetBytes(Serialize(layout, report)));

    public static string Serialize(KeyboardLayout source, ConversionReport report)
    {
        var layout = ComposeCompiler.Compile(source).Layout;
        var sb = new StringBuilder();
        var symbolsName = Regex.Replace(layout.Metadata.DllName.ToLowerInvariant(), "[^a-z0-9_]", "_");
        sb.Append("// Generated by kbdking. Install: copy to /usr/share/X11/xkb/symbols/").Append(symbolsName).Append('\n');
        sb.Append("// and select it with: setxkbmap ").Append(symbolsName).Append('\n');
        sb.Append("default partial alphanumeric_keys modifier_keys\n");
        sb.Append("xkb_symbols \"basic\" {\n");
        sb.Append("    name[Group1] = \"").Append(layout.Metadata.Name.Replace("\"", "'", StringComparison.Ordinal)).Append("\";\n\n");

        var customDead = new List<string>();
        foreach (var entry in PhysicalKeyCodes.All)
        {
            if (entry.XkbName is not { } name) continue;
            var target = entry.Extended ? layout.ScanCodes.E0.GetValueOrDefault((byte)entry.ScanCode, ScanCodeTarget.None) : layout.ScanCodes[entry.ScanCode];
            var vk = target.Flags.HasFlag(ScanCodeFlags.Numpad) && entry.ScanCode == 0x53 ? VirtualKeys.Decimal : target.VirtualKey;
            var key = target.IsNone ? null : layout.FindKey(vk);
            if (key is null) continue;

            var syms = new List<string>();
            foreach (var level in Levels)
            {
                var o = layout.Modifiers.Canonicalize(level) is { } c ? key.Outputs.GetValueOrDefault(c) : null;
                syms.Add(o is null ? "NoSymbol" : Keysym(o, report, customDead));
            }
            while (syms.Count > 1 && syms[^1] == "NoSymbol") syms.RemoveAt(syms.Count - 1);
            var type = syms.Count > 2 ? (key.Attributes.HasFlag(KeyAttributes.CapsLock) ? "FOUR_LEVEL_SEMIALPHABETIC" : "FOUR_LEVEL") : null;
            if (key.Attributes.HasFlag(KeyAttributes.CapsLockAltGr) && syms.Count > 2) type = "FOUR_LEVEL_ALPHABETIC";
            sb.Append("    key <").Append(name).Append("> { ");
            if (type is not null) sb.Append("type[Group1] = \"").Append(type).Append("\", ");
            sb.Append("[ ").Append(string.Join(", ", syms)).Append(" ] };\n");
            if (key.CapsOutputs is not null) report.Warn($"Key {key.Name}: separate Caps Lock characters are not expressible in XKB symbols.");
        }
        sb.Append("\n    include \"level3(ralt_switch)\"\n};\n");

        if (layout.DeadKeys.Any(d => d.Entries.Count > 0))
            report.Warn("XKB takes dead-key compositions from the Compose table; kbdking writes them to a companion .XCompose file.");
        foreach (var c in customDead.Distinct())
            report.Warn($"Dead key {c} has no XKB dead_* keysym; it is exported as a plain character.");
        if (layout.Modifiers.Columns.Any(c => !Levels.Contains(c) && c.Bits is not ModifierBits.Ctrl and not (ModifierBits.Shift | ModifierBits.Ctrl)))
            report.Warn("Shift states beyond Shift, AltGr and Shift+AltGr are not exported.");
        return sb.ToString();
    }

    /// <summary>The dead-key compositions as .XCompose lines, to put in ~/.XCompose next to the symbols file.</summary>
    public static string WriteXCompose(KeyboardLayout source)
    {
        var layout = ComposeCompiler.Compile(source).Layout;
        var sb = new StringBuilder("# Dead-key compositions generated by kbdking\ninclude \"%L\"\n\n");
        string Sym(char accent) => Diacritics.Find(accent)?.XkbDeadKey ?? XComposeFile.CharToKeysym(accent);
        // Only dead keys that a key produces start a sequence; chained states are expanded into longer sequences.
        var starts = layout.Keys.SelectMany(k => k.Outputs.Values).Where(o => o.IsDead).Select(o => o.Accent).Distinct();
        foreach (var accent in starts) Expand(accent, "<" + Sym(accent) + ">", 0);
        void Expand(char accent, string prefix, int depth)
        {
            if (depth > 4 || layout.FindDeadKey(accent) is not { } d) return;
            foreach (var e in d.Entries)
            {
                var isDeadKey = layout.Keys.Any(k => k.Outputs.Values.Any(o => o.IsDead && o.Accent == e.Base));
                var step = prefix + " <" + (isDeadKey ? Sym(e.Base) : XComposeFile.CharToKeysym(e.Base)) + ">";
                if (e.Chained) Expand(e.Result, step, depth + 1);
                else sb.Append(step).Append(" : ").Append(XComposeFile.FormatResult(e.Result.ToString())).Append('\n');
            }
        }
        return sb.ToString();
    }

    private static string Keysym(KeyOutput o, ConversionReport report, List<string> customDead)
    {
        if (o.IsDead)
        {
            if (Diacritics.Find(o.Accent) is { } d) return d.XkbDeadKey;
            customDead.Add($"U+{(int)o.Accent:X4}");
            return XComposeFile.CharToKeysym(o.Accent);
        }
        if (o.Text.Length > 1)
        {
            if (char.IsSurrogatePair(o.Text, 0) && o.Text.Length == 2) return $"U{char.ConvertToUtf32(o.Text, 0):X}";
            report.Warn($"Ligature \"{o.Text}\" can't be one XKB keysym; only its first character is exported.");
        }
        return XComposeFile.CharToKeysym(o.Text[0]);
    }

    // ---------------------------------------------------------------- reading

    [GeneratedRegex(@"key\s*<(?<name>[A-Z0-9]+)>\s*\{(?<body>[^}]*)\}\s*;", RegexOptions.Singleline)]
    private static partial Regex KeyRegex();

    [GeneratedRegex(@"\[(?<syms>[^\]]*)\]")]
    private static partial Regex SymbolsRegex();

    [GeneratedRegex(@"name\s*\[\s*Group1\s*\]\s*=\s*""(?<name>[^""]*)""")]
    private static partial Regex NameRegex();

    [GeneratedRegex(@"symbols\s*\[\s*Group1\s*\]\s*=\s*\[(?<syms>[^\]]*)\]")]
    private static partial Regex Group1SymbolsRegex();

    /// <summary>True if the bracket at <paramref name="index"/> is part of a named attribute such as type[...] or actions[Group1] = [...].</summary>
    private static bool IsAttributeList(string body, int index)
    {
        var i = index - 1;
        while (i >= 0 && char.IsWhiteSpace(body[i])) i--;
        if (i >= 0 && body[i] == '=')
        {
            i--;
            while (i >= 0 && char.IsWhiteSpace(body[i])) i--;
            return i >= 0 && body[i] == ']';   // something[GroupN] = [ ... ]
        }
        return i >= 0 && char.IsLetterOrDigit(body[i]); // type[GroupN], actions[...]
    }

    public KeyboardLayout Read(Stream input, ConversionReport report)
    {
        using var reader = new StreamReader(input, Encoding.UTF8, detectEncodingFromByteOrderMarks: true);
        return Parse(reader.ReadToEnd(), report);
    }

    public static KeyboardLayout Parse(string text, ConversionReport report)
    {
        try
        {
            return ParseCore(text, report);
        }
        catch (Exception ex) when (ex is ArgumentException or FormatException or IndexOutOfRangeException or InvalidOperationException)
        {
            throw new LayoutFormatException($"Invalid XKB symbols file: {ex.Message}", ex);
        }
    }

    private static KeyboardLayout ParseCore(string text, ConversionReport report)
    {
        // Strip comments, then use the first xkb_symbols block.
        text = Regex.Replace(text, @"//[^\n]*", "");
        var start = text.IndexOf("xkb_symbols", StringComparison.Ordinal);
        if (start < 0) throw new LayoutFormatException("No xkb_symbols block found.");
        var open = text.IndexOf('{', start);
        if (open < 0) throw new LayoutFormatException("The xkb_symbols block has no '{'.");
        var depth = 0;
        var end = open;
        for (; end < text.Length; end++)
        {
            if (text[end] == '{') depth++;
            else if (text[end] == '}' && --depth == 0) break;
        }
        var block = text[open..Math.Min(end + 1, text.Length)];

        var layout = LayoutTemplates.UnitedStates();
        layout.Metadata = new LayoutMetadata { Name = NameRegex().Match(block) is { Success: true } m ? m.Groups["name"].Value : "Imported layout" };
        layout.Flags = LocaleFlags.None;
        layout.Keys.RemoveAll(k => !VirtualKeys.IsImplicitControlKey(k.VirtualKey) && k.VirtualKey is not VirtualKeys.Space and not VirtualKeys.Decimal);
        layout.DeadKeys.Clear();
        if (block.Contains("include", StringComparison.Ordinal))
            report.Warn("'include' statements are not followed; keys not defined in this file keep the US layout.");

        var unknown = new HashSet<string>();
        foreach (Match km in KeyRegex().Matches(block))
        {
            var entry = PhysicalKeyCodes.ByXkbName(km.Groups["name"].Value);
            if (entry is null) continue;
            var target = entry.Extended ? layout.ScanCodes.E0.GetValueOrDefault((byte)entry.ScanCode, ScanCodeTarget.None) : layout.ScanCodes[entry.ScanCode];
            if (target.IsNone) continue;
            var vk = target.Flags.HasFlag(ScanCodeFlags.Numpad) && entry.ScanCode == 0x53 ? VirtualKeys.Decimal : target.VirtualKey;
            var body = km.Groups["body"].Value;
            // The symbols of group 1: "symbols[Group1] = [...]" if present, otherwise the first bare [...]
            // ("type[Group1]", "actions[...]" and later groups use brackets too).
            var symsMatch = Group1SymbolsRegex().Match(body) is { Success: true } g1 ? g1
                : SymbolsRegex().Matches(body).FirstOrDefault(m => !m.Groups["syms"].Value.Trim().StartsWith("Group", StringComparison.Ordinal)
                    && !IsAttributeList(body, m.Index));
            if (symsMatch is null) continue;
            var syms = symsMatch.Groups["syms"].Value.Split(',', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries);
            var key = layout.GetOrAddKey(vk);
            key.Outputs.Clear();
            for (var i = 0; i < syms.Length && i < Levels.Length; i++)
            {
                var o = ParseKeysym(syms[i], unknown);
                if (o is null) continue;
                layout.SetOutput(vk, Levels[i], o);
            }
            var b = key.Outputs.GetValueOrDefault(ShiftState.Base);
            var s = key.Outputs.GetValueOrDefault(ShiftState.Shift);
            if (b is { IsDead: false, Text.Length: 1 } && s is { IsDead: false, Text.Length: 1 } && char.IsLower(b.Text[0]) && s.Text == b.Text.ToUpperInvariant())
                key.Attributes |= KeyAttributes.CapsLock;
            if (body.Contains("ALPHABETIC\"", StringComparison.Ordinal) && !body.Contains("SEMIALPHABETIC", StringComparison.Ordinal))
                key.Attributes |= KeyAttributes.CapsLockAltGr;
        }
        if (unknown.Count > 0) report.Warn($"Unknown keysyms skipped: {string.Join(", ", unknown.Order())}.");

        // Linux composes dead keys through the Compose table; give Windows explicit compositions.
        foreach (var d in layout.DeadKeys)
        {
            var diacritic = Diacritics.Find(d.Accent);
            if (diacritic is null) continue;
            foreach (var (bc, result) in Diacritics.Compositions(diacritic.Combining)) d.Set(bc, result);
            d.Set(' ', diacritic.Spacing ?? diacritic.Combining);
            d.Name ??= diacritic.Name.ToUpperInvariant();
        }
        if (layout.DeadKeys.Count > 0)
            report.Warn("Dead-key compositions were generated from Unicode data; custom compositions from your Compose file are not included.");
        LayoutFixups.AssignLetterVirtualKeys(layout);
        layout.NormalizeShiftStates();
        return layout;
    }

    private static KeyOutput? ParseKeysym(string sym, HashSet<string> unknown)
    {
        if (sym is "NoSymbol" or "VoidSymbol") return null;
        if (sym.StartsWith("dead_", StringComparison.Ordinal))
        {
            if (Diacritics.FindXkb(sym) is { } d) return KeyOutput.Dead(d.Spacing ?? d.Combining);
            unknown.Add(sym);
            return null;
        }
        static bool Valid(int c) => c is > 0 and <= 0x10FFFF and not (>= 0xD800 and <= 0xDFFF);
        if (sym.Length > 1 && sym[0] == 'U' && int.TryParse(sym.AsSpan(1), NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var cp) && Valid(cp))
            return KeyOutput.Of(char.ConvertFromUtf32(cp));
        if (sym.StartsWith("0x", StringComparison.OrdinalIgnoreCase) && int.TryParse(sym.AsSpan(2), NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var raw) && raw is >= 0x01000000 and <= 0x0110FFFF && Valid(raw - 0x01000000))
            return KeyOutput.Of(char.ConvertFromUtf32(raw - 0x01000000));
        if (XComposeFile.KeysymToChar(sym) is { } c) return KeyOutput.Of(c);
        unknown.Add(sym);
        return null;
    }
}
