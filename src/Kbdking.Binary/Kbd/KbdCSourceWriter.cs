using System.Globalization;
using System.Text;
using Kbdking.Core.Formats;
using Kbdking.Core.Model;

namespace Kbdking.Binary.Kbd;

/// <summary>
/// Writes the layout as a self-contained C file declaring the same kbd.h tables kbdking writes in binary.
/// Used to cross-check the PE writer against a real compiler (clang-cl + lld-link in CI), and useful for
/// people who want to build a layout with their own toolchain.
/// </summary>
internal static class KbdCSourceWriter
{
    public static string Write(KeyboardLayout layout)
    {
        var plan = KbdTablesPlan.Create(Core.Compose.ComposeCompiler.Compile(layout).Layout);
        var sb = new StringBuilder();
        void L(string s = "") => sb.Append(s).Append('\n');
        static string H(int v) => "0x" + v.ToString("x4", CultureInfo.InvariantCulture);
        static string B(int v) => "0x" + v.ToString("x2", CultureInfo.InvariantCulture);

        var title = layout.Metadata.Name.Replace("*/", "* /", StringComparison.Ordinal).Replace('\r', ' ').Replace('\n', ' ');
        L($"/* {title} — generated by kbdking. Do not edit; edit the .kbdking file instead.");
        L(" *");
        L(" * 64-bit build (clang-cl / MSVC):");
        L(" *   cl /c /O1 /GS- /Zl layout.c");
        L($" *   link /dll /noentry /nodefaultlib /machine:x64 /export:KbdLayerDescriptor /out:{layout.Metadata.DllName.ToLowerInvariant()}.dll layout.obj");
        L(" * 32-bit WOW64 build (MSVC): add /DKBDKING_WOW64 and use /machine:x86.");
        L(" */");
        L();
        L("typedef unsigned char BYTE;");
        L("typedef unsigned short WORD;");
        L("typedef unsigned short USHORT;");
        L("typedef unsigned short WCHAR;");
        L("typedef unsigned int DWORD;");
        L();
        L("#ifdef KBDKING_WOW64");
        L("#define KBD_LONG_POINTER __ptr64");
        L("#else");
        L("#define KBD_LONG_POINTER");
        L("#endif");
        L();
        L("/* win32k copies only the .data section of a layout DLL, so every table and string goes there. */");
        L("#pragma section(\".data\", read, write)");
        L("#define KBD_DATA __declspec(allocate(\".data\"))");
        L();
        L("typedef struct { BYTE Vk; BYTE ModBits; } VK_TO_BIT;");
        L($"typedef struct {{ VK_TO_BIT *KBD_LONG_POINTER pVkToBit; WORD wMaxModBits; BYTE ModNumber[{plan.Modifiers.ModNumber.Count}]; }} MODIFIERS;");
        foreach (var w in plan.Tables.Select(t => t.Width).Distinct())
            L($"typedef struct {{ BYTE VirtualKey; BYTE Attributes; WCHAR wch[{w}]; }} VK_TO_WCHARS{w};");
        L("typedef struct { void *KBD_LONG_POINTER pVkToWchars; BYTE nModifications; BYTE cbSize; } VK_TO_WCHAR_TABLE;");
        L("typedef struct { DWORD dwBoth; WCHAR wchComposed; USHORT uFlags; } DEADKEY;");
        L("typedef struct { BYTE vsc; WCHAR *KBD_LONG_POINTER pwsz; } VSC_LPWSTR;");
        L("typedef struct { BYTE Vsc; USHORT Vk; } VSC_VK;");
        if (plan.Ligatures.Count > 0)
            L($"typedef struct {{ BYTE VirtualKey; WORD ModificationNumber; WCHAR wch[{plan.LigatureMax}]; }} LIGATURE;");
        L("typedef struct {");
        L("    MODIFIERS *KBD_LONG_POINTER pCharModifiers;");
        L("    VK_TO_WCHAR_TABLE *KBD_LONG_POINTER pVkToWcharTable;");
        L("    DEADKEY *KBD_LONG_POINTER pDeadKey;");
        L("    VSC_LPWSTR *KBD_LONG_POINTER pKeyNames;");
        L("    VSC_LPWSTR *KBD_LONG_POINTER pKeyNamesExt;");
        L("    WCHAR *KBD_LONG_POINTER *KBD_LONG_POINTER pKeyNamesDead;");
        L("    USHORT *KBD_LONG_POINTER pusVSCtoVK;");
        L("    BYTE bMaxVSCtoVK;");
        L("    VSC_VK *KBD_LONG_POINTER pVSCtoVK_E0;");
        L("    VSC_VK *KBD_LONG_POINTER pVSCtoVK_E1;");
        L("    DWORD fLocaleFlags;");
        L("    BYTE nLgMax;");
        L("    BYTE cbLgEntry;");
        L("    void *KBD_LONG_POINTER pLigature;");
        L("    DWORD dwType;");
        L("    DWORD dwSubType;");
        L("} KBDTABLES;");
        L();

        // Strings
        var stringIndex = 0;
        string Str(string s)
        {
            var name = "str" + stringIndex++;
            L($"static KBD_DATA WCHAR {name}[] = {{ {string.Join(", ", s.Select(c => H(c)).Append("0"))} }};");
            return name;
        }
        var keyNames = plan.KeyNames.Select(p => (p.Key, Str(p.Value))).ToList();
        var keyNamesExt = plan.KeyNamesExt.Select(p => (p.Key, Str(p.Value))).ToList();
        var deadNames = plan.DeadKeyNames.Select(Str).ToList();
        L();

        // Modifiers
        L("static KBD_DATA VK_TO_BIT aVkToBits[] = {");
        foreach (var v in plan.Modifiers.VkToBits) L($"    {{ {B(v.VirtualKey)}, {B((int)v.Bits)} }},");
        L("    { 0, 0 }");
        L("};");
        L();
        L($"static KBD_DATA MODIFIERS CharModifiers = {{ aVkToBits, {plan.Modifiers.ModNumber.Count - 1}, {{ {string.Join(", ", plan.Modifiers.ModNumber.Select(n => B(n)))} }} }};");
        L();

        // Character tables
        foreach (var t in plan.Tables)
        {
            L($"static KBD_DATA VK_TO_WCHARS{t.Width} {t.Name}[] = {{");
            foreach (var row in t.Rows)
            {
                var comment = row.VirtualKey == KbdConstants.ContinuationVk ? "" : $" /* {VirtualKeys.GetName(row.VirtualKey)} */";
                L($"    {{ {B(row.VirtualKey)}, {B(row.Attributes)}, {{ {string.Join(", ", row.Chars.Select(c => H(c)))} }} }},{comment}");
            }
            L($"    {{ 0, 0, {{ {string.Join(", ", Enumerable.Repeat("0", t.Width))} }} }}");
            L("};");
            L();
        }
        L("static KBD_DATA VK_TO_WCHAR_TABLE aVkToWcharTable[] = {");
        foreach (var t in plan.Tables) L($"    {{ {t.Name}, {t.Width}, sizeof({t.Name}[0]) }},");
        L("    { 0, 0, 0 }");
        L("};");
        L();

        if (plan.Ligatures.Count > 0)
        {
            L("static KBD_DATA LIGATURE aLigature[] = {");
            foreach (var lg in plan.Ligatures)
            {
                var chars = Enumerable.Range(0, plan.LigatureMax).Select(i => i < lg.Text.Length ? (int)lg.Text[i] : KbdConstants.WchNone);
                L($"    {{ {B(lg.VirtualKey)}, {lg.Column}, {{ {string.Join(", ", chars.Select(H))} }} }},");
            }
            L($"    {{ 0, 0, {{ {string.Join(", ", Enumerable.Repeat("0", plan.LigatureMax))} }} }}");
            L("};");
            L();
        }

        if (plan.DeadKeys.Count > 0)
        {
            L("static KBD_DATA DEADKEY aDeadKey[] = {");
            foreach (var d in plan.DeadKeys)
                L($"    {{ 0x{(uint)(d.Base | d.Accent << 16):x8}, {H(d.Result)}, {(d.Chained ? "1" : "0")} }},");
            L("    { 0, 0, 0 }");
            L("};");
            L();
        }

        void Names(string name, List<(byte Key, string Str)> names)
        {
            if (names.Count == 0) return;
            L($"static KBD_DATA VSC_LPWSTR {name}[] = {{");
            foreach (var (sc, s) in names) L($"    {{ {B(sc)}, {s} }},");
            L("    { 0, 0 }");
            L("};");
            L();
        }
        Names("aKeyNames", keyNames);
        Names("aKeyNamesExt", keyNamesExt);
        if (deadNames.Count > 0)
        {
            L("static KBD_DATA WCHAR *KBD_LONG_POINTER aKeyNamesDead[] = {");
            foreach (var s in deadNames) L($"    {s},");
            L("    0");
            L("};");
            L();
        }

        L($"static KBD_DATA USHORT ausVK[] = {{ {string.Join(", ", plan.ScanCodes.DefaultIfEmpty((ushort)0).Select(v => H(v)))} }};");
        L();
        void Prefixed(string name, List<(byte Scan, ushort Vk)> list)
        {
            L($"static KBD_DATA VSC_VK {name}[] = {{");
            foreach (var (sc, vk) in list) L($"    {{ {B(sc)}, {H(vk)} }},");
            L("    { 0, 0 }");
            L("};");
            L();
        }
        Prefixed("aE0VscToVk", plan.ScanCodesE0);
        Prefixed("aE1VscToVk", plan.ScanCodesE1);

        L("static KBD_DATA KBDTABLES KbdTables = {");
        L("    &CharModifiers,");
        L("    aVkToWcharTable,");
        L($"    {(plan.DeadKeys.Count > 0 ? "aDeadKey" : "0")},");
        L($"    {(keyNames.Count > 0 ? "aKeyNames" : "0")},");
        L($"    {(keyNamesExt.Count > 0 ? "aKeyNamesExt" : "0")},");
        L($"    {(deadNames.Count > 0 ? "aKeyNamesDead" : "0")},");
        L("    ausVK,");
        L($"    {plan.ScanCodes.Count},");
        L("    aE0VscToVk,");
        L("    aE1VscToVk,");
        L($"    0x{plan.LocaleFlags:x8},");
        L($"    {plan.LigatureMax}, {plan.LigatureEntrySize}, {(plan.Ligatures.Count > 0 ? "aLigature" : "0")},");
        L($"    {plan.KeyboardType}, {plan.KeyboardSubType}");
        L("};");
        L();
        L("__declspec(dllexport) KBDTABLES *KBD_LONG_POINTER KbdLayerDescriptor(void)");
        L("{");
        L("    return &KbdTables;");
        L("}");
        return sb.ToString();
    }
}
