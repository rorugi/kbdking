using System.Globalization;
using System.Text;
using Keyservant.Core.Formats;

namespace Keyservant.Core.Compose;

/// <summary>
/// Reads and writes compose sequences in the X11 <c>.XCompose</c> format, also used by WinCompose:
/// <c>&lt;Multi_key&gt; &lt;period&gt; &lt;r&gt; : "ṛ" U1E5B # comment</c>.
/// </summary>
public static class XComposeFile
{
    public static List<ComposeSequence> Parse(string text, ConversionReport report)
    {
        var result = new List<ComposeSequence>();
        var lineNo = 0;
        int skippedKeysyms = 0, skippedOther = 0;
        foreach (var raw in text.Split('\n'))
        {
            lineNo++;
            var line = raw.Trim();
            if (line.Length == 0 || line[0] == '#') continue;
            if (line.StartsWith("include", StringComparison.Ordinal))
            {
                report.Warn($"Line {lineNo}: 'include' is not followed; import the included file separately.");
                continue;
            }
            var colon = FindColon(line);
            if (colon < 0) { skippedOther++; continue; }
            var lhs = line[..colon];
            var rhs = line[(colon + 1)..].Trim();

            var keysyms = new List<string>();
            var i = 0;
            while ((i = lhs.IndexOf('<', i)) >= 0)
            {
                var end = lhs.IndexOf('>', i);
                if (end < 0) break;
                keysyms.Add(lhs[(i + 1)..end]);
                i = end + 1;
            }
            if (keysyms.Count < 2 || keysyms[0] != "Multi_key") { skippedOther++; continue; }

            var keys = new StringBuilder();
            var ok = true;
            foreach (var ks in keysyms.Skip(1))
            {
                if (KeysymToChar(ks) is { } c) keys.Append(c);
                else { ok = false; break; }
            }
            if (!ok) { skippedKeysyms++; continue; }

            var value = ParseResult(rhs);
            if (value is null) { skippedOther++; continue; }
            result.Add(new ComposeSequence(keys.ToString(), value));
        }
        if (skippedKeysyms > 0) report.Warn($"Skipped {skippedKeysyms} sequences that use keys without a character (dead_* keys, function keys, unknown keysyms).");
        if (skippedOther > 0) report.Warn($"Skipped {skippedOther} lines that are not <Multi_key> sequences.");
        return result;
    }

    public static string Write(IEnumerable<ComposeSequence> sequences)
    {
        var sb = new StringBuilder("# Generated by Keyservant\n");
        foreach (var s in sequences)
        {
            sb.Append("<Multi_key>");
            foreach (var c in s.Keys) sb.Append(" <").Append(CharToKeysym(c)).Append('>');
            sb.Append(" : ").Append(FormatResult(s.Result)).Append('\n');
        }
        return sb.ToString();
    }

    /// <summary>The right-hand side of a compose line: the quoted, escaped result and its keysym, e.g. <c>"\"" U0022</c>.</summary>
    internal static string FormatResult(string result)
    {
        var sb = new StringBuilder("\"");
        sb.Append(result.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal)).Append('"');
        if (result.Length > 0 && (!char.IsSurrogate(result[0]) || char.IsSurrogatePair(result, 0)))
            sb.Append(CultureInfo.InvariantCulture, $" U{char.ConvertToUtf32(result, 0):X4}");
        return sb.ToString();
    }

    /// <summary>The ':' between the keys and the result: outside quotes and outside &lt;keysym&gt; brackets.</summary>
    private static int FindColon(string line)
    {
        var inQuote = false;
        var inAngle = false;
        for (var i = 0; i < line.Length; i++)
        {
            var c = line[i];
            if (c == '"' && (i == 0 || line[i - 1] != '\\')) inQuote = !inQuote;
            else if (inQuote) continue;
            else if (c == '<') inAngle = true;
            else if (c == '>') inAngle = false;
            else if (c == ':' && !inAngle) return i;
        }
        return -1;
    }

    private static string? ParseResult(string rhs)
    {
        var hash = -1;
        var inQuote = false;
        for (var i = 0; i < rhs.Length; i++)
        {
            if (rhs[i] == '"' && (i == 0 || rhs[i - 1] != '\\')) inQuote = !inQuote;
            if (!inQuote && rhs[i] == '#') { hash = i; break; }
        }
        if (hash >= 0) rhs = rhs[..hash].Trim();
        if (rhs.StartsWith('"'))
        {
            var sb = new StringBuilder();
            for (var i = 1; i < rhs.Length; i++)
            {
                if (rhs[i] == '\\' && i + 1 < rhs.Length) { sb.Append(rhs[++i]); continue; }
                if (rhs[i] == '"') return sb.Length > 0 ? sb.ToString() : null;
                sb.Append(rhs[i]);
            }
            return null;
        }
        // Keysym only, e.g. ": U1E5B" or ": ssharp".
        var first = rhs.Split(' ', StringSplitOptions.RemoveEmptyEntries).FirstOrDefault();
        return first is null ? null : KeysymToChar(first)?.ToString();
    }

    /// <summary>Maps an X11 keysym name to the character it types; null for keys without a character.</summary>
    public static char? KeysymToChar(string keysym)
    {
        if (keysym.Length == 1) return keysym[0];
        if (keysym.Length >= 5 && keysym[0] == 'U' && int.TryParse(keysym.AsSpan(1), NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var cp))
            return cp is > 0 and <= 0xFFFF and not (>= 0xD800 and <= 0xDFFF) ? (char)cp : null;
        if (s_names.TryGetValue(keysym, out var c)) return c;
        return null;
    }

    public static string CharToKeysym(char c)
    {
        if (char.IsAsciiLetterOrDigit(c)) return c.ToString();
        if (s_reverse.TryGetValue(c, out var name)) return name;
        return $"U{(int)c:X4}";
    }

    private static readonly Dictionary<string, char> s_names = BuildNames();
    private static readonly Dictionary<char, string> s_reverse = s_names.GroupBy(p => p.Value).ToDictionary(g => g.Key, g => g.First().Key);

    private static Dictionary<string, char> BuildNames()
    {
        var d = new Dictionary<string, char>(StringComparer.Ordinal)
        {
            ["space"] = ' ', ["exclam"] = '!', ["quotedbl"] = '"', ["numbersign"] = '#', ["dollar"] = '$', ["percent"] = '%',
            ["ampersand"] = '&', ["apostrophe"] = '\'', ["quoteright"] = '\'', ["parenleft"] = '(', ["parenright"] = ')',
            ["asterisk"] = '*', ["plus"] = '+', ["comma"] = ',', ["minus"] = '-', ["period"] = '.', ["slash"] = '/',
            ["colon"] = ':', ["semicolon"] = ';', ["less"] = '<', ["equal"] = '=', ["greater"] = '>', ["question"] = '?',
            ["at"] = '@', ["bracketleft"] = '[', ["backslash"] = '\\', ["bracketright"] = ']', ["asciicircum"] = '^',
            ["underscore"] = '_', ["grave"] = '`', ["quoteleft"] = '`', ["braceleft"] = '{', ["bar"] = '|', ["braceright"] = '}',
            ["asciitilde"] = '~', ["EuroSign"] = '€',
        };
        // Latin-1 supplement, U+00A0..U+00FF, in order.
        string[] latin1 =
        [
            "nobreakspace", "exclamdown", "cent", "sterling", "currency", "yen", "brokenbar", "section", "diaeresis", "copyright",
            "ordfeminine", "guillemotleft", "notsign", "hyphen", "registered", "macron", "degree", "plusminus", "twosuperior",
            "threesuperior", "acute", "mu", "paragraph", "periodcentered", "cedilla", "onesuperior", "masculine", "guillemotright",
            "onequarter", "onehalf", "threequarters", "questiondown", "Agrave", "Aacute", "Acircumflex", "Atilde", "Adiaeresis",
            "Aring", "AE", "Ccedilla", "Egrave", "Eacute", "Ecircumflex", "Ediaeresis", "Igrave", "Iacute", "Icircumflex",
            "Idiaeresis", "ETH", "Ntilde", "Ograve", "Oacute", "Ocircumflex", "Otilde", "Odiaeresis", "multiply", "Oslash",
            "Ugrave", "Uacute", "Ucircumflex", "Udiaeresis", "Yacute", "THORN", "ssharp", "agrave", "aacute", "acircumflex",
            "atilde", "adiaeresis", "aring", "ae", "ccedilla", "egrave", "eacute", "ecircumflex", "ediaeresis", "igrave", "iacute",
            "icircumflex", "idiaeresis", "eth", "ntilde", "ograve", "oacute", "ocircumflex", "otilde", "odiaeresis", "division",
            "oslash", "ugrave", "uacute", "ucircumflex", "udiaeresis", "yacute", "thorn", "ydiaeresis",
        ];
        for (var i = 0; i < latin1.Length; i++) d[latin1[i]] = (char)(0xA0 + i);
        d["guillemetleft"] = '«';
        d["guillemetright"] = '»';
        return d;
    }
}
