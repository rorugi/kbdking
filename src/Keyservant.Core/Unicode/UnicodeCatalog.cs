using System.Globalization;
using System.IO.Compression;
using System.Text;

namespace Keyservant.Core.Unicode;

/// <summary>A character and its Unicode name.</summary>
public sealed record UnicodeCharInfo(int CodePoint, string Name)
{
    public string Text => char.ConvertFromUtf32(CodePoint);

    public string Code => $"U+{CodePoint:X4}";

    public UnicodeCategory Category => CharUnicodeInfo.GetUnicodeCategory(CodePoint);

    /// <summary>True for combining marks, which are shown on a dotted circle.</summary>
    public bool IsMark => Category is UnicodeCategory.NonSpacingMark or UnicodeCategory.SpacingCombiningMark or UnicodeCategory.EnclosingMark;

    public string Display => IsMark ? "◌" + Text : Text;

    public override string ToString() => $"{Code} {Name}";
}

/// <summary>
/// Unicode character names and search, from a table embedded in the assembly
/// (generated by tools/generate-unicode-names.py). Works offline.
/// </summary>
public static class UnicodeCatalog
{
    private static readonly Lazy<(Dictionary<int, string> Names, List<UnicodeCharInfo> All, string Version)> s_data = new(Load);

    /// <summary>The Unicode version of the name table.</summary>
    public static string Version => s_data.Value.Version;

    /// <summary>All named characters, in code point order.</summary>
    public static IReadOnlyList<UnicodeCharInfo> All => s_data.Value.All;

    private static (Dictionary<int, string>, List<UnicodeCharInfo>, string) Load()
    {
        var names = new Dictionary<int, string>();
        var all = new List<UnicodeCharInfo>();
        var version = "";
        using var stream = typeof(UnicodeCatalog).Assembly.GetManifestResourceStream("Keyservant.Core.Unicode.UnicodeNames.txt.gz")
            ?? throw new InvalidOperationException("The Unicode name table is missing from the assembly.");
        using var gz = new GZipStream(stream, CompressionMode.Decompress);
        using var reader = new StreamReader(gz, Encoding.UTF8);
        while (reader.ReadLine() is { } line)
        {
            if (line.StartsWith("#unicode ", StringComparison.Ordinal)) { version = line[9..]; continue; }
            var semi = line.IndexOf(';');
            if (semi <= 0) continue;
            var cp = int.Parse(line.AsSpan(0, semi), NumberStyles.HexNumber, CultureInfo.InvariantCulture);
            var name = line[(semi + 1)..];
            names[cp] = name;
            all.Add(new UnicodeCharInfo(cp, name));
        }
        return (names, all, version);
    }

    /// <summary>The name of a code point, including algorithmically named ones; null if unassigned or unknown.</summary>
    public static string? GetName(int codePoint)
    {
        if (s_data.Value.Names.TryGetValue(codePoint, out var name)) return name;
        if (codePoint is >= 0xAC00 and <= 0xD7A3) return "HANGUL SYLLABLE " + HangulSyllableName(codePoint);
        string? Algorithmic(string prefix) => CharUnicodeInfo.GetUnicodeCategory(codePoint) == UnicodeCategory.OtherLetter ? $"{prefix}-{codePoint:X4}" : null;
        if (codePoint is >= 0x4E00 and <= 0x9FFF or >= 0x3400 and <= 0x4DBF or >= 0x20000 and <= 0x3134F or >= 0x31350 and <= 0x323AF or >= 0x2EBF0 and <= 0x2EE5D)
            return Algorithmic("CJK UNIFIED IDEOGRAPH");
        if (codePoint is >= 0xF900 and <= 0xFAFF or >= 0x2F800 and <= 0x2FA1F) return Algorithmic("CJK COMPATIBILITY IDEOGRAPH");
        if (codePoint is >= 0x17000 and <= 0x187FF or >= 0x18D00 and <= 0x18D08) return Algorithmic("TANGUT IDEOGRAPH");
        if (codePoint is >= 0x18B00 and <= 0x18CD5) return Algorithmic("KHITAN SMALL SCRIPT CHARACTER");
        if (codePoint is >= 0x1B170 and <= 0x1B2FB) return Algorithmic("NUSHU CHARACTER");
        if (codePoint is >= 0xE000 and <= 0xF8FF) return "PRIVATE USE";
        return null;
    }

    public static UnicodeCharInfo? Get(int codePoint) => GetName(codePoint) is { } name ? new UnicodeCharInfo(codePoint, name) : null;

    /// <summary>
    /// Searches by name words ("a macron", "dot below"), code ("U+0101", "1E6D") or by pasting the character
    /// itself. All words must match; one-letter words must match a whole word, longer ones a word start.
    /// </summary>
    public static IReadOnlyList<UnicodeCharInfo> Search(string query, int limit = 100)
    {
        query = query.Trim();
        if (query.Length == 0) return [];
        var results = new List<UnicodeCharInfo>();

        // Pasted characters.
        if (!query.Any(char.IsWhiteSpace) && query.EnumerateRunes().Count() <= 4 && !query.All(char.IsAsciiLetterOrDigit))
        {
            foreach (var r in query.EnumerateRunes())
            {
                if (Get(r.Value) is { } info && !results.Contains(info)) results.Add(info);
            }
            if (results.Count > 0) return results;
        }

        // Code point.
        var prefixed = query.StartsWith("U+", StringComparison.OrdinalIgnoreCase) || query.StartsWith("\\u", StringComparison.OrdinalIgnoreCase);
        var hex = prefixed ? query[2..] : query;
        // A bare word like "cafe" or "dead" is a name, not a code; bare codes need a digit (1E6D).
        if ((prefixed || hex.Any(char.IsAsciiDigit)) && hex.Length is >= 4 and <= 6 && int.TryParse(hex, NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var cp) && Get(cp) is { } exact)
            results.Add(exact);

        var words = query.ToUpperInvariant().Split([' ', '-', ',', '+'], StringSplitOptions.RemoveEmptyEntries);
        var scored = new List<(UnicodeCharInfo Info, int Score)>();
        foreach (var info in All)
        {
            var nameWords = info.Name.Split(' ', '-');
            var ok = true;
            foreach (var w in words)
            {
                var hit = false;
                foreach (var nw in nameWords)
                {
                    if (w.Length == 1 ? nw == w : nw.StartsWith(w, StringComparison.Ordinal)) { hit = true; break; }
                }
                if (!hit) { ok = false; break; }
            }
            if (!ok) continue;
            // Prefer short names (fewer extra words), then Latin, then lower code points.
            var score = (nameWords.Length - words.Length) * 10 + (info.Name.StartsWith("LATIN", StringComparison.Ordinal) ? 0 : 5);
            if (info.Name.Equals(query, StringComparison.OrdinalIgnoreCase)) score = -100;
            scored.Add((info, score));
        }
        foreach (var (info, _) in scored.OrderBy(s => s.Score).ThenBy(s => s.Info.CodePoint))
        {
            if (results.Count >= limit) break;
            if (!results.Contains(info)) results.Add(info);
        }
        return results;
    }

    private static string HangulSyllableName(int cp)
    {
        string[] lead = ["G", "GG", "N", "D", "DD", "R", "M", "B", "BB", "S", "SS", "", "J", "JJ", "C", "K", "T", "P", "H"];
        string[] vowel = ["A", "AE", "YA", "YAE", "EO", "E", "YEO", "YE", "O", "WA", "WAE", "OE", "YO", "U", "WEO", "WE", "WI", "YU", "EU", "YI", "I"];
        string[] tail = ["", "G", "GG", "GS", "N", "NJ", "NH", "D", "L", "LG", "LM", "LB", "LS", "LT", "LP", "LH", "M", "B", "BS", "S", "SS", "NG", "J", "C", "K", "T", "P", "H"];
        var s = cp - 0xAC00;
        return lead[s / (21 * 28)] + vowel[s % (21 * 28) / 28] + tail[s % 28];
    }
}
